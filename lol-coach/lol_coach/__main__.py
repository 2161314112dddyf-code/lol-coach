import argparse
import json
import re
from pathlib import Path

from .http import EvidenceClient, save_json
from .champion import normalize

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description="Public static-data evidence audit")
    parser.add_argument("--offline", action="store_true", help="Use verified cache only")
    parser.add_argument("--refresh", action="store_true")
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("audit-sources")
    sub.add_parser("versions")
    fetch = sub.add_parser("fetch-champion")
    fetch.add_argument("--patch", required=True)
    fetch.add_argument("--champion", default="Ivern")
    fetch.add_argument("--locale", default="en_US")
    extract = sub.add_parser("extract-map")
    extract.add_argument("--game-dir", required=True)
    extract.add_argument("--patch", required=True)
    extract.add_argument("--skin", default="Default")
    query = sub.add_parser("query-map")
    query.add_argument("--patch", required=True)
    query.add_argument("--skin", default="Default")
    query.add_argument("--grid-source", choices=("container", "skin"), default="container")
    query.add_argument("--x", type=float, required=True)
    query.add_argument("--z", type=float, required=True)
    args = parser.parse_args()
    if args.command in ("extract-map", "query-map"):
        try:
            from .map_pipeline import extract_map, load_bundle
            if args.command == "extract-map":
                extract_map(ROOT, args.game_dir, args.patch, args.skin, args.offline, args.refresh)
            else:
                grid, manifest = load_bundle(ROOT, args.patch, args.skin)
                from .map_selection import query_selected_grid
                result = query_selected_grid(ROOT, manifest, args.x, args.z, args.grid_source)
                print(json.dumps(result, ensure_ascii=False, indent=2))
        except (ValueError, OSError, ImportError) as exc:
            print(f"Map operation failed: {exc}")
            return 1
        return 0
    client = EvidenceClient(ROOT / "data")
    options = dict(offline=args.offline, refresh=args.refresh)
    if args.command == "audit-sources":
        sources = json.loads((ROOT / "docs/source_candidates.json").read_text(encoding="utf-8"))["sources"]
        results = []
        for source in sources:
            record, _ = client.fetch(source["id"], source["url"], expect_json=source["id"] in ("ddragon-versions", "meraki-ivern", "meta-api", "live-sample"), **options)
            record["license_review_status"] = source.get("license_review_status", "not_reviewed")
            record["limitations"].append("Access does not prove field correctness, current-version compatibility or reuse permission")
            results.append(record)
            print(source["id"], record["status"], record["http_status"], flush=True)
        save_json(ROOT / "reports/source_audit.json", results)
        lines = ["# HTTP source audit", "", "Generated by audit-sources. See source_verification.md for manual interpretation.", "", "|Source|HTTP|Status|Version evidence|Raw evidence (relative to data/)|", "|---|---|---|---|---|"]
        lines += [f"|{r['source_id']}|{r['http_status']}|{r['status']}|{r['content_version']}|{r['evidence_path']}|" for r in results]
        lines += ["", "Failures and attempts are retained in data/attempts/. Cached fetch times remain the original retrieval times.", "License, target client patch, NGRID parsing, action timing and real replay parsing are not validated by HTTP access."]
        (ROOT / "reports/source_audit.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
        return 0
    versions_record, versions = client.fetch("ddragon-versions", "https://ddragon.leagueoflegends.com/api/versions.json", expect_json=True, **options)
    if not isinstance(versions, list) or not versions or not all(isinstance(v, str) for v in versions):
        print("Version list unavailable or invalid:", versions_record["status"])
        return 1
    if args.command == "versions":
        print(json.dumps(versions[:20]))
        return 0
    if args.patch not in versions or not re.fullmatch(r"[A-Za-z0-9]+", args.champion) or not re.fullmatch(r"[a-z]{2}_[A-Z]{2}", args.locale):
        print("Invalid patch, champion identifier or locale")
        return 1
    url = f"https://ddragon.leagueoflegends.com/cdn/{args.patch}/data/{args.locale}/champion/{args.champion}.json"
    record, payload = client.fetch("ddragon-champion", url, expect_json=True, **options)
    try:
        result = normalize(payload, args.champion, args.patch, record)
    except ValueError as exc:
        record["limitations"].append(str(exc))
        record["status"] = "validation_failed"
        save_json(ROOT / "reports/champion_failure.json", record)
        print(str(exc))
        return 1
    target = ROOT / f"data/normalized/{args.patch}/{args.locale}/{args.champion}.json"
    record["content_version"] = result["data_version"]
    record["status"] = "base_fields_validated" if result["data_version"] else "fields_mapped_version_unverified"
    record["versions_evidence"] = versions_record
    save_json(target.with_suffix(".manifest.json"), record)
    save_json(target, result)
    print(str(target))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
